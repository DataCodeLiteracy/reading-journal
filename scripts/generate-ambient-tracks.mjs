/**
 * public/audio 의 mp3/m4a/ogg/wav 를 스캔해
 * src/generated/readingTimerAmbientTracks.generated.ts 를 만듭니다.
 * 파일만 추가한 뒤 yarn dev / yarn build 하면 타이머 배경음에 반영됩니다.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")
const audioDir = path.join(root, "public", "audio")
const outDir = path.join(root, "src", "generated")
const outFile = path.join(outDir, "readingTimerAmbientTracks.generated.ts")

const AUDIO_EXT = new Set([".mp3", ".m4a", ".ogg", ".wav", ".aac", ".flac"])

/** 기존 localStorage 선택값 유지용 — 번호 → 예전 id */
const LEGACY_ID_BY_ORDER = {
  1: "early-light",
  2: "staring",
  3: "blue-wednesday",
  4: "snowfall",
  5: "purrple-cat",
  6: "ambient-6",
  7: "ambient-7",
  8: "ambient-8",
}

/** 표시용 한글 라벨(파일명 본문 대신 쓰고 싶을 때) */
const KO_LABEL_BY_FILENAME = {
  "1.distant-land.mp3": "먼 땅",
  "2.lingering-gaze.mp3": "머무는 시선",
  "3.phosphorescence.mp3": "인광",
  "4.forest.mp3": "숲의",
  "5.purple-cat.mp3": "보라색 고양이",
  "6.snowfall.mp3": "눈 내림",
  "7.early-light.mp3": "이른 빛",
  "8.blue-wednesday.mp3": "푸른 수요일",
}

function labelFromFileName(fileName) {
  if (KO_LABEL_BY_FILENAME[fileName]) return KO_LABEL_BY_FILENAME[fileName]
  const base = fileName.replace(/\.[^.]+$/i, "").trim()
  const body = base.replace(/^\d+\.\s*/, "").trim()
  return body || fileName
}

function idForOrder(order) {
  return LEGACY_ID_BY_ORDER[order] ?? `ambient-${order}`
}

function parseOrder(fileName) {
  const m = /^(\d+)\./.exec(fileName)
  if (!m) return null
  const n = Number(m[1])
  return Number.isInteger(n) && n >= 1 ? n : null
}

if (!fs.existsSync(audioDir)) {
  console.warn(`[generate-ambient-tracks] missing ${audioDir}`)
  process.exit(0)
}

const files = fs
  .readdirSync(audioDir)
  .filter((name) => {
    const ext = path.extname(name).toLowerCase()
    return AUDIO_EXT.has(ext) && !name.startsWith(".")
  })

const numbered = []
for (const fileName of files) {
  const order = parseOrder(fileName)
  if (order === null) {
    console.warn(
      `[generate-ambient-tracks] skip (번호 접두 없음): ${fileName}`,
    )
    continue
  }
  numbered.push({
    order,
    fileName,
    id: idForOrder(order),
    label: labelFromFileName(fileName),
  })
}

numbered.sort((a, b) => a.order - b.order || a.fileName.localeCompare(b.fileName, "ko"))

// 같은 번호가 둘이면 경고 후 파일명 순 첫 것만
const seen = new Set()
const unique = []
for (const t of numbered) {
  if (seen.has(t.order)) {
    console.warn(
      `[generate-ambient-tracks] duplicate order ${t.order}, skip ${t.fileName}`,
    )
    continue
  }
  seen.add(t.order)
  unique.push(t)
}

const tracksLiteral = unique
  .map((t) => {
    const src = `/audio/${encodeURIComponent(t.fileName)}`
    return `  {\n    id: ${JSON.stringify(t.id)},\n    label: ${JSON.stringify(t.label)},\n    src: ${JSON.stringify(src)},\n    order: ${t.order},\n  }`
  })
  .join(",\n")

const content = `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/generate-ambient-tracks.mjs
 * Do not edit by hand. Add files under public/audio as \`N.이름.mp3\` then run yarn generate:ambient (or yarn dev / yarn build).
 */
export type GeneratedAmbientTrack = {
  id: string
  label: string
  src: string
  order: number
}

export const GENERATED_AMBIENT_TRACKS: GeneratedAmbientTrack[] = [
${tracksLiteral}
]
`

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(outFile, content, "utf8")
console.log(
  `[generate-ambient-tracks] wrote ${unique.length} tracks → ${path.relative(root, outFile)}`,
)
